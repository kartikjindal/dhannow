-- DhanNow PLAN Phase 7: grievance tickets, the working-day calendar their SLA counts on, and the loan hold
-- (dispute) audit trail.

-- 1. Holidays the complaint SLA skips (CC-64), ADMIN-maintained. Weekends are always skipped.
create table holiday_calendar (
    day         date primary key,
    name        varchar(128) not null,
    created_by  varchar(64)  not null,
    created_at  timestamp(6) with time zone not null default now()
);

-- 2. The complaint. ticket_no DN-GRV-00001…; acknowledged within 2 working days, in review within 5, resolved
--    within 15 calendar days (all in IST, end of day). A breach is flagged once per milestone by the SLA sweep.
create sequence complaint_ticket_seq;
create table complaint (
    id                  bigint generated by default as identity primary key,
    ticket_no           varchar(16) not null unique
                        default ('DN-GRV-' || lpad(nextval('complaint_ticket_seq')::text, 5, '0')),
    customer_id         bigint not null,
    loan_id             bigint references loan (id),
    category            varchar(32) not null check (category in ('PAYMENT', 'CHARGES', 'COLLECTIONS_CONDUCT',
                        'LOAN_DISPUTE', 'EXTENSION_NOT_REQUESTED', 'DATA_PRIVACY', 'APP_OR_SERVICE', 'OTHER')),
    body                text not null,
    attachment_key      varchar(512),
    source              varchar(16) not null check (source in ('BORROWER', 'STAFF', 'SYSTEM')),
    status              varchar(16) not null default 'OPEN'
                        check (status in ('OPEN', 'ACKNOWLEDGED', 'IN_REVIEW', 'RESOLVED', 'ESCALATED')),
    ack_due_at          timestamp(6) with time zone not null,
    review_due_at       timestamp(6) with time zone not null,
    resolve_due_at      timestamp(6) with time zone not null,
    acknowledged_at     timestamp(6) with time zone,
    review_started_at   timestamp(6) with time zone,
    resolved_at         timestamp(6) with time zone,
    escalated_at        timestamp(6) with time zone,
    resolution_note     text,
    assigned_to         bigint,
    ack_breached_at     timestamp(6) with time zone,
    review_breached_at  timestamp(6) with time zone,
    resolve_breached_at timestamp(6) with time zone,
    version             bigint not null default 0,
    created_by          varchar(64) not null,
    created_at          timestamp(6) with time zone not null default now(),
    updated_at          timestamp(6) with time zone,
    check (status <> 'RESOLVED' or (resolved_at is not null and resolution_note is not null))
);
create index idx_complaint_customer on complaint (customer_id);
create index idx_complaint_open on complaint (status) where status <> 'RESOLVED';

-- Every step on a ticket, append-only: who moved it, from what, to what, and why.
create table complaint_event (
    id            bigint generated by default as identity primary key,
    complaint_id  bigint not null references complaint (id),
    action        varchar(32) not null,
    from_status   varchar(16),
    to_status     varchar(16),
    note          text,
    actor_id      varchar(64) not null,
    actor_role    varchar(32) not null,
    at            timestamp(6) with time zone not null default now()
);
create index idx_complaint_event_complaint on complaint_event (complaint_id);

-- 3. Every hold placed on or lifted from a loan (DISPUTED from a complaint or staff), append-only.
create table loan_hold_event (
    id            bigint generated by default as identity primary key,
    loan_id       bigint not null references loan (id),
    from_hold     varchar(16) not null,
    to_hold       varchar(16) not null,
    reason        text not null,
    complaint_id  bigint references complaint (id),
    actor_id      varchar(64) not null,
    actor_role    varchar(32) not null,
    at            timestamp(6) with time zone not null default now()
);
create index idx_loan_hold_event_loan on loan_hold_event (loan_id);

create function append_only() returns trigger language plpgsql as $$
begin
    raise exception '% is append-only', tg_table_name;
end $$;
create trigger trg_complaint_event_append_only before update or delete on complaint_event
    for each row execute function append_only();
create trigger trg_loan_hold_event_append_only before update or delete on loan_hold_event
    for each row execute function append_only();
