-- DhanNow PLAN Phase 6a: repayment schedules. Every loan gets a v1 BULLET schedule when the Accountant
-- confirms the disbursal. A later extension or EMI adds a new version and supersedes the previous one;
-- no schedule's terms are ever edited, and the original stays as it was written.
create table repayment_schedule (
    id                bigint generated by default as identity primary key,
    loan_id           bigint not null references loan (id),
    version           int not null check (version >= 1),
    kind              varchar(16) not null check (kind in ('BULLET', 'EXTENSION', 'EMI')),
    parent_version_id bigint references repayment_schedule (id),
    status            varchar(16) not null default 'ACTIVE' check (status in ('ACTIVE', 'SUPERSEDED')),
    created_by        varchar(255),
    reason_code       varchar(64),
    created_at        timestamp(6) with time zone not null default now(),
    unique (loan_id, version)
);
create unique index uq_repayment_schedule_active on repayment_schedule (loan_id) where status = 'ACTIVE';

-- Money columns are what falls due on the instalment. A BULLET instalment is the principal only: the
-- fee, GST and interest were deducted at disbursal.
create table schedule_instalment (
    id              bigint generated by default as identity primary key,
    schedule_id     bigint not null references repayment_schedule (id),
    seq             int not null check (seq >= 1),
    due_date        date not null,
    due_at          timestamp(6) with time zone not null,
    principal_paise bigint not null check (principal_paise >= 0),
    interest_paise  bigint not null default 0 check (interest_paise >= 0),
    fee_paise       bigint not null default 0 check (fee_paise >= 0),
    gst_paise       bigint not null default 0 check (gst_paise >= 0),
    paid_paise      bigint not null default 0 check (paid_paise >= 0),
    status          varchar(16) not null default 'DUE' check (status in ('DUE', 'PAID')),
    unique (schedule_id, seq)
);

-- Immutable terms: a schedule may only be superseded, an instalment may only record what was paid.
create function repayment_schedule_frozen() returns trigger language plpgsql as $$
begin
    if tg_op = 'DELETE' then
        raise exception 'repayment_schedule % cannot be deleted', old.id;
    end if;
    if (new.loan_id, new.version, new.kind, new.parent_version_id, new.created_by, new.reason_code, new.created_at)
            is distinct from (old.loan_id, old.version, old.kind, old.parent_version_id, old.created_by,
            old.reason_code, old.created_at)
            or (old.status = 'SUPERSEDED' and new.status <> 'SUPERSEDED') then
        raise exception 'repayment_schedule % is immutable: add a new version', old.id;
    end if;
    return new;
end $$;
create trigger trg_repayment_schedule_frozen before update or delete on repayment_schedule
    for each row execute function repayment_schedule_frozen();

create function schedule_instalment_frozen() returns trigger language plpgsql as $$
begin
    if tg_op = 'DELETE' then
        raise exception 'schedule_instalment % cannot be deleted', old.id;
    end if;
    if (new.schedule_id, new.seq, new.due_date, new.due_at, new.principal_paise, new.interest_paise,
            new.fee_paise, new.gst_paise)
            is distinct from (old.schedule_id, old.seq, old.due_date, old.due_at, old.principal_paise,
            old.interest_paise, old.fee_paise, old.gst_paise) then
        raise exception 'schedule_instalment % is immutable: add a new schedule version', old.id;
    end if;
    return new;
end $$;
create trigger trg_schedule_instalment_frozen before update or delete on schedule_instalment
    for each row execute function schedule_instalment_frozen();
