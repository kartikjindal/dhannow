-- DhanNow PLAN Phase 5: documents.
--
-- 1. loan_document holds every DhanNow loan document (KFS, SANCTION, AGREEMENT, SCHEDULE, …), each
--    versioned and stored in S3 with its hash. The KFS, sanction letter and agreement are issued on the
--    offer, before any loan row exists, so a row belongs to an application, a loan, or both.
--    application_document stays for KYC uploads (and the navix e-sign source copy).
alter table loan_document alter column loan_id drop not null;

alter table loan_document
    add column application_id      bigint references loan_application (id),
    add column version             int not null default 1 check (version >= 1),
    add column pricing_version_id  bigint references pricing_config (id),
    -- The principal the document states: a KFS acknowledged for another amount is not this offer's KFS.
    add column amount_paise        bigint,
    add column s3_key              varchar(512),
    add column sha256              char(64),
    add column created_at          timestamp(6) with time zone not null default now(),
    add column accepted_at         timestamp(6) with time zone,
    add column accepted_ip         varchar(64),
    add column acceptance_evidence jsonb,
    add constraint loan_document_owner_check check (loan_id is not null or application_id is not null);

create unique index uq_loan_document_application_type_version
    on loan_document (application_id, type, version) where application_id is not null;
create index idx_loan_document_application_id on loan_document (application_id);

-- 2. Offer validity (CC-02): an offer lapses at offer_valid_until; the next KFS re-quotes on the
--    current pricing. Set when the pricing is frozen (sanction or re-apply). Null = no expiry (pre-V100).
alter table loan_application add column offer_valid_until timestamp(6) with time zone;

alter table product_config add column offer_validity_days int not null default 3 check (offer_validity_days >= 1);

create or replace function product_config_terms_frozen() returns trigger language plpgsql as $$
begin
    if old.status <> 'DRAFT' and (new.version, new.allowed_amounts_paise, new.min_paise, new.max_paise,
            new.due_cutoff_time, new.timezone, new.one_live_loan, new.late_blocks_upgrade_days,
            new.overdue_review_dpd, new.offer_validity_days)
            is distinct from (old.version, old.allowed_amounts_paise, old.min_paise, old.max_paise,
            old.due_cutoff_time, old.timezone, old.one_live_loan, old.late_blocks_upgrade_days,
            old.overdue_review_dpd, old.offer_validity_days) then
        raise exception 'product_config % is %: its terms are frozen, add a new version', old.version, old.status;
    end if;
    return new;
end $$;

-- 3. Staff reads of a loan document are audited (append-only).
create table loan_document_access (
    id               bigint generated by default as identity primary key,
    loan_document_id bigint not null references loan_document (id),
    actor_id         varchar(255) not null,
    actor_role       varchar(64) not null,
    at               timestamp(6) with time zone not null
);
create index idx_loan_document_access_document_id on loan_document_access (loan_document_id);
