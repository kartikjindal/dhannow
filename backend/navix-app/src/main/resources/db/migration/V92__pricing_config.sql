-- DhanNow PLAN Phase 1: versioned pricing. Every money figure on an offer and its loan is computed
-- from ONE row here, frozen on the application at offer time (V94) and copied to the loan at
-- disbursal, so activating a new version never changes an existing offer or loan.
--
-- A version's terms are fixed once it leaves DRAFT (trigger below): to change pricing, insert a new
-- version and activate it; only status (ACTIVE -> RETIRED) and the approval fields may change on a
-- live row. At most one row is ACTIVE.
create table pricing_config (
    id              bigint generated by default as identity primary key,
    version         int          not null unique,
    pf_rate         numeric(6,4) not null check (pf_rate >= 0),
    gst_rate        numeric(6,4) not null check (gst_rate >= 0),
    daily_rate      numeric(6,4) not null check (daily_rate >= 0),
    tenure_days     int          not null check (tenure_days > 0),
    interest_mode   varchar(16)  not null check (interest_mode in ('UPFRONT', 'ACCRUED')),
    penal_enabled   boolean      not null,
    penal_rate      numeric(6,4) not null check (penal_rate >= 0),
    penal_cap_days  int          not null check (penal_cap_days >= 0),
    prepay_rebate   boolean      not null,
    -- Only one rule exists today: round each figure to a whole paisa, half up (LoanMath).
    rounding        varchar(16)  not null default 'HALF_UP_PAISA' check (rounding = 'HALF_UP_PAISA'),
    effective_from  timestamp(6) with time zone not null,
    approved_by     bigint,
    approved_at     timestamp(6) with time zone,
    status          varchar(16)  not null check (status in ('DRAFT', 'ACTIVE', 'RETIRED')),
    created_at      timestamp(6) with time zone not null default now(),
    created_by      varchar(255),
    updated_at      timestamp(6) with time zone,
    updated_by      varchar(255)
);

create unique index pricing_config_one_active on pricing_config ((true)) where status = 'ACTIVE';

create function pricing_config_terms_frozen() returns trigger language plpgsql as $$
begin
    if old.status <> 'DRAFT' and (new.version, new.pf_rate, new.gst_rate, new.daily_rate, new.tenure_days,
            new.interest_mode, new.penal_enabled, new.penal_rate, new.penal_cap_days, new.prepay_rebate,
            new.rounding, new.effective_from)
            is distinct from (old.version, old.pf_rate, old.gst_rate, old.daily_rate, old.tenure_days,
            old.interest_mode, old.penal_enabled, old.penal_rate, old.penal_cap_days, old.prepay_rebate,
            old.rounding, old.effective_from) then
        raise exception 'pricing_config % is %: its terms are frozen, add a new version', old.version, old.status;
    end if;
    return new;
end $$;

create trigger pricing_config_terms_frozen before update on pricing_config
    for each row execute function pricing_config_terms_frozen();

