-- DhanNow PLAN Phase 6a: payments.
--
-- 1. payment_allocation: how each verified payment was split by the waterfall (config
--    navix.payments.waterfall, penal → principal; interest is prepaid at disbursal). EXCESS is money
--    nothing was owed for; it is also opened as a refund_case. Written once per payment.
create table payment_allocation (
    id           bigint generated by default as identity primary key,
    payment_id   bigint not null references payment (id),
    loan_id      bigint not null references loan (id),
    component    varchar(16) not null check (component in ('PENAL', 'INTEREST', 'PRINCIPAL', 'EXCESS')),
    amount_paise bigint not null check (amount_paise > 0),
    created_at   timestamp(6) with time zone not null default now(),
    unique (payment_id, component)
);
create index idx_payment_allocation_loan_id on payment_allocation (loan_id);

-- 2. idempotency_key (CC-22): one row per client key. A replay with the same key and the same request
--    returns the first result (result_id); the same key with a different request is refused.
create table idempotency_key (
    key          varchar(128) primary key,
    scope        varchar(64) not null,
    request_hash char(64) not null,
    result_id    bigint,
    created_at   timestamp(6) with time zone not null default now()
);

-- 3. refund_case (CC-08, CC-11): money taken that nothing was owed for. The navix NACH overpayment
--    register (mandate_debit.overpayment) and DhanNow overpayments both land here, owned by finance.
create table refund_case (
    id               bigint generated by default as identity primary key,
    loan_id          bigint not null references loan (id),
    customer_id      bigint not null,
    payment_id       bigint references payment (id),
    mandate_debit_id bigint references mandate_debit (id),
    amount_paise     bigint not null check (amount_paise > 0),
    reason           varchar(32) not null check (reason in ('OVERPAYMENT', 'NACH_AFTER_CLOSE')),
    status           varchar(16) not null default 'OPEN' check (status in ('OPEN', 'REFUNDED', 'CANCELLED')),
    created_at       timestamp(6) with time zone not null default now(),
    created_by       varchar(255),
    updated_at       timestamp(6) with time zone,
    updated_by       varchar(255),
    constraint refund_case_source_check check (payment_id is not null or mandate_debit_id is not null)
);
create unique index uq_refund_case_payment on refund_case (payment_id) where payment_id is not null;
create unique index uq_refund_case_mandate_debit on refund_case (mandate_debit_id) where mandate_debit_id is not null;
create index idx_refund_case_status on refund_case (status);

-- 4. CC-07: a UTR is unique across every payment (rejected ones aside, so a borrower can resubmit
--    the right proof). References are stored normalised: no spaces, upper case.
update payment set txn_ref = nullif(upper(regexp_replace(txn_ref, '\s', '', 'g')), '') where txn_ref is not null;
create unique index uq_payment_txn_ref on payment (txn_ref) where txn_ref is not null and status <> 'REJECTED';
