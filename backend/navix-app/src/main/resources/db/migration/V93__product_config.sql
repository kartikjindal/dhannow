-- DhanNow PLAN Phase 1: versioned product rules. allowed_amounts_paise is the credit ladder (Phase 2):
-- level n may borrow up to the n-th amount, and only these amounts are selectable. Frozen on the
-- application next to the pricing version (V94). Same rules as pricing_config: terms fixed once out of
-- DRAFT, at most one ACTIVE row.
create table product_config (
    id                        bigint generated by default as identity primary key,
    version                   int          not null unique,
    allowed_amounts_paise     bigint[]     not null check (cardinality(allowed_amounts_paise) > 0),
    min_paise                 bigint       not null check (min_paise > 0),
    max_paise                 bigint       not null,
    due_cutoff_time           time         not null default '23:59:59',
    timezone                  varchar(64)  not null default 'Asia/Kolkata',
    one_live_loan             boolean      not null default true,
    late_blocks_upgrade_days  int          not null default 1,
    status                    varchar(16)  not null check (status in ('DRAFT', 'ACTIVE', 'RETIRED')),
    created_at                timestamp(6) with time zone not null default now(),
    created_by                varchar(255),
    updated_at                timestamp(6) with time zone,
    updated_by                varchar(255),
    check (max_paise >= min_paise),
    check (allowed_amounts_paise[1] >= min_paise
           and allowed_amounts_paise[cardinality(allowed_amounts_paise)] <= max_paise)
);

create unique index product_config_one_active on product_config ((true)) where status = 'ACTIVE';

create function product_config_terms_frozen() returns trigger language plpgsql as $$
begin
    if old.status <> 'DRAFT' and (new.version, new.allowed_amounts_paise, new.min_paise, new.max_paise,
            new.due_cutoff_time, new.timezone, new.one_live_loan, new.late_blocks_upgrade_days)
            is distinct from (old.version, old.allowed_amounts_paise, old.min_paise, old.max_paise,
            old.due_cutoff_time, old.timezone, old.one_live_loan, old.late_blocks_upgrade_days) then
        raise exception 'product_config % is %: its terms are frozen, add a new version', old.version, old.status;
    end if;
    return new;
end $$;

create trigger product_config_terms_frozen before update on product_config
    for each row execute function product_config_terms_frozen();

