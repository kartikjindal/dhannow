-- DhanNow PLAN Phase 2: the credit ladder. One row per customer once their first loan is disbursed (no
-- row reads as level 1). Level n may borrow up to product_config.allowed_amounts_paise[n]; max_paise
-- records that amount when the level was set.
create table credit_level (
    customer_id  bigint       primary key,
    level        smallint     not null check (level >= 1),
    max_paise    bigint       not null,
    updated_at   timestamp(6) with time zone not null default now()
);

-- Every level decision, including "no change" after a late repayment, so the borrower's ladder can be
-- explained line by line. A manual exception names the ADMIN who approved it and a reason code.
create table credit_level_history (
    id           bigint generated by default as identity primary key,
    customer_id  bigint       not null,
    from_level   smallint,
    to_level     smallint     not null,
    reason       varchar(32)  not null
        check (reason in ('FIRST_LOAN', 'ON_TIME_REPAID', 'LATE_REPAID_NO_CHANGE', 'MANUAL_EXCEPTION')),
    loan_id      bigint,
    approved_by  bigint,
    reason_code  varchar(64),
    at           timestamp(6) with time zone not null default now(),
    created_at   timestamp(6) with time zone not null default now(),
    created_by   varchar(255),
    updated_at   timestamp(6) with time zone,
    updated_by   varchar(255),
    check (reason <> 'MANUAL_EXCEPTION' or (approved_by is not null and reason_code is not null))
);

create index credit_level_history_customer on credit_level_history (customer_id, at);

-- A closed loan moves the ladder once, however often its closure is recomputed.
create unique index credit_level_history_one_per_closure on credit_level_history (loan_id)
    where reason in ('ON_TIME_REPAID', 'LATE_REPAID_NO_CHANGE');
